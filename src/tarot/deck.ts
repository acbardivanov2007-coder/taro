function buildSuit(
  suit: Exclude<TarotSuit, 'major'>,
  suitRuGenitive: string,
  suitEn: string,
  element: TarotElement,
  seeds: MinorCardSeed[],
): TarotCard[] {
  return seeds.map((seed, idx) => {
    const rank = RANKS[idx];
    const numStr = String(rank.number).padStart(2, '0');
    const enSlug = rank.enPrefix.toLowerCase();
    return {
      id: `${suit}-${numStr}-${enSlug}`,
      number: rank.number,
      roman: rank.roman,
      nameRu: `${rank.ruPrefix} ${suitRuGenitive}`,
      nameEn: `${rank.enPrefix} of ${suitEn}`,
      arcana: 'minor',
      suit,
      element,
      ...seed,
    };
  });
}

